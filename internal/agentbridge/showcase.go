package agentbridge

import (
	"context"
	"fmt"
	"net/url"
	"strings"
	"unicode/utf8"
)

// ValidateShowcase checks display data only. Item IDs never select recipients;
// URLs are passed to the backend without fetching or uploading their contents.
func ValidateShowcase(text string, spec map[string]any) error {
	invalid := func(message string) error { return bridgeError("SHOWCASE_INVALID", message, false) }
	if strings.TrimSpace(text) == "" || utf8.RuneCountInString(text) > 5000 {
		return invalid("showcase requires 1–5000 characters of plain text")
	}
	for key := range spec {
		if key != "items" {
			return invalid("showcase accepts only items; version is generated by the backend")
		}
	}
	items, ok := spec["items"].([]any)
	if !ok || len(items) < 1 || len(items) > 10 {
		return invalid("showcase requires 1–10 ordered items")
	}
	limits := map[string]int{"id": 100, "image_url": 2000, "title": 100, "subtitle": 200, "description": 1000, "note": 500}
	seen := make(map[string]bool)
	for index, value := range items {
		item, ok := value.(map[string]any)
		if !ok {
			return invalid(fmt.Sprintf("showcase item %d must be an object", index+1))
		}
		for key, value := range item {
			limit, known := limits[key]
			text, isString := value.(string)
			if !known || !isString || utf8.RuneCountInString(text) > limit {
				return invalid(fmt.Sprintf("showcase item %d has an invalid %s field", index+1, key))
			}
		}
		for _, key := range []string{"id", "image_url", "title"} {
			value, ok := item[key].(string)
			if !ok || strings.TrimSpace(value) == "" {
				return invalid(fmt.Sprintf("showcase item %d requires %s", index+1, key))
			}
		}
		id := strings.TrimSpace(item["id"].(string))
		if seen[id] {
			return invalid("showcase item IDs must be unique within the message")
		}
		seen[id] = true
		imageURL, err := url.Parse(strings.TrimSpace(item["image_url"].(string)))
		if err != nil || imageURL.Scheme != "https" || imageURL.Hostname() == "" || imageURL.User != nil {
			return invalid("showcase images require HTTPS URLs without embedded credentials")
		}
	}
	return nil
}

func (client *APIClient) sendShowcase(ctx context.Context, route Route, params SendParams) (SendResult, error) {
	if IsDiscoveryInquiryRoute(route) || (route.Source != "" && route.Source != "agenrena") {
		return SendResult{}, bridgeError("CHANNEL_MESSAGE_TYPE_UNSUPPORTED", "showcases require an Agenrena conversation", false)
	}
	if params.InputRequest != nil || len(params.Media) > 0 || (params.Format != "" && params.Format != "plain") {
		return SendResult{}, bridgeError("SHOWCASE_INVALID", "showcase requires plain text without inputRequest or attached media", false)
	}
	if err := ValidateShowcase(params.Text, params.Showcase); err != nil {
		return SendResult{}, err
	}
	if params.ClientMessageID == "" {
		id, err := NewOperationID()
		if err != nil {
			return SendResult{}, err
		}
		params.ClientMessageID = id
	}
	if len(params.ClientMessageID) > 100 {
		return SendResult{}, bridgeError("MESSAGE_INVALID", "clientMessageId exceeds 100 characters", false)
	}
	body := outboundMessageBody(route, params.ClientMessageID, params.ReplyTo)
	body["message_type"], body["text"], body["text_format"] = "showcase", params.Text, "plain"
	body["showcase"] = params.Showcase
	id, err := client.sendOutboundMessage(ctx, body)
	if err != nil {
		return SendResult{}, err
	}
	if id == "" {
		return SendResult{}, bridgeError("DELIVERY_UNKNOWN", "showcase send returned no message id; delivery outcome is unknown", false)
	}
	return SendResult{MessageID: id, ClientMessageID: params.ClientMessageID}, nil
}
